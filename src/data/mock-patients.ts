/**
 * Calculates all dashboard metrics dynamically from the given patient dataset.
 * Adheres strictly to the requirement: "Do not invent mortality or recovery outcomes
 * for patients without a final recorded outcome."
 */
export function calculateDashboardMetrics(
  patients: Patient[],
  facilityCapacity = FACILITY_CAPACITY
): DashboardMetrics {
  const admittedPatients = patients.filter((p) => p.isCurrentlyAdmitted);
  const totalAdmitted = admittedPatients.length;
  const occupiedBeds = totalAdmitted;
  const availableBeds = Math.max(facilityCapacity - occupiedBeds, 0);
  const occupancyRatePct = Number(
    ((occupiedBeds / facilityCapacity) * 100).toFixed(1)
  );

  const pendingTemperatureChecks = admittedPatients.filter(
    (p) => p.todayVitals.status === "pending"
  ).length;

  const completedTemperatureChecks = admittedPatients.filter(
    (p) => p.todayVitals.status !== "pending"
  ).length;

  const pendingDoctorVisits = admittedPatients.filter(
    (p) => p.doctorVisitToday.status === "pending"
  ).length;

  const completedDoctorVisits = admittedPatients.filter(
    (p) => p.doctorVisitToday.status === "completed"
  ).length;

  const dischargeEligiblePatients = admittedPatients.filter(
    (p) => p.status === "cleared"
  ).length;

  const highAttentionPatientsCount = admittedPatients.filter(
    (p) =>
      p.riskLevel === "critical" ||
      p.riskLevel === "high" ||
      p.status === "flagged" ||
      (p.todayVitals.temperatureCelsius !== null &&
        p.todayVitals.temperatureCelsius >= 38.2) ||
      (p.todayVitals.oxygenSaturationPct !== null &&
        p.todayVitals.oxygenSaturationPct < 95)
  ).length;

  // Final outcome calculations: only for patients with recorded final outcome!
  const patientsWithFinalOutcome = patients.filter(
    (p) => p.finalOutcome !== null && p.finalOutcome !== undefined
  );
  const totalFinalOutcomes = patientsWithFinalOutcome.length;
  const deceasedCount = patientsWithFinalOutcome.filter(
    (p) => p.finalOutcome === "deceased"
  ).length;
  const recoveredCount = patientsWithFinalOutcome.filter(
    (p) => p.finalOutcome === "recovered"
  ).length;

  const mortalityRatePct =
    totalFinalOutcomes > 0
      ? Number(((deceasedCount / totalFinalOutcomes) * 100).toFixed(1))
      : 0;

  const treatmentSuccessRatePct =
    totalFinalOutcomes > 0
      ? Number(((recoveredCount / totalFinalOutcomes) * 100).toFixed(1))
      : 0;

  return {
    totalAdmittedPatients: totalAdmitted,
    occupiedBeds,
    availableBeds,
    facilityCapacity,
    occupancyRatePct,
    pendingTemperatureChecks,
    completedTemperatureChecks,
    pendingDoctorVisits,
    completedDoctorVisits,
    dischargeEligiblePatients,
    highAttentionPatientsCount,
    mortalityRatePct,
    mortalityBenchmarkPct: 15.0,
    mortalityTotalOutcomes: totalFinalOutcomes,
    mortalityDeceasedCount: deceasedCount,
    treatmentSuccessRatePct,
    treatmentSuccessBenchmarkPct: 85.0,
    treatmentSuccessRecoveredCount: recoveredCount,
  };
}

